create or replace temporary view rc_pola_cust as select '^[0-9]+([.][0-9]+)?[Ee][+-]?[0-9]+$' as p;

update public.customers c
   set ktp            = case when nullif(x.ktp,'') is not null
                              and (coalesce(c.ktp,'')='' or c.ktp ~ (select p from rc_pola_cust))
                             then x.ktp else c.ktp end,
       npwp           = case when nullif(x.npwp,'') is not null
                              and (coalesce(c.npwp,'')='' or c.npwp ~ (select p from rc_pola_cust))
                             then x.npwp else c.npwp end,
       account_number = case when nullif(x.no_rek,'') is not null
                              and (coalesce(c.account_number,'')='' or c.account_number ~ (select p from rc_pola_cust))
                             then x.no_rek else c.account_number end,
       account_name   = case when nullif(x.nama_rek,'') is not null and coalesce(c.account_name,'')=''
                             then x.nama_rek else c.account_name end,
       bank           = case when nullif(x.bank,'') is not null and coalesce(c.bank,'')=''
                             then x.bank else c.bank end,
       top_text       = case when nullif(x.top_text,'') is not null
                              and (coalesce(c.top_text,'')='' or c.top_text ~ (select p from rc_pola_cust))
                             then x.top_text else c.top_text end,
       contact_person = case when nullif(x.contact_person,'') is not null and coalesce(c.contact_person,'')=''
                             then x.contact_person else c.contact_person end,
       updated_at     = now()
  from rc_sumber_cust x
 where c.customer_code = x.customer_code;

